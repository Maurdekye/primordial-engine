#!/usr/bin/env bash
# Re-records every committed record that depends on Box3D's arithmetic, from source, in one
# command (D58, double precision on; rule of 2026-10-31: no hand-edited logs). Whichever branch
# lands second on main reruns it on the merged tree and commits the result.
#   PE_HEAVY=<lock wrapper> nice -n 19 bash scripts/rebless_physics_records.sh [--no-linux]
# Do not run it under heavy.sh: heavy.sh is not re-entrant, and every cargo command below
# already takes the org-wide lock itself (PE_HEAVY for run_determinism.sh, `low` in
# run_p2_2_tests.sh). Everything else inherits the idle priority from `nice`.
#
# What it writes (docs/d58-double-precision.md lists the records and why each moves):
#  1. spikes/out/vdw/{goldens,trace,images,rollback}-{vdw,off}-win-{release,debug}.*: the physics
#     spike's baselines, which check_par_determinism.sh, run_determinism.sh and pe-physics'
#     spike_records compare against. Generated by the spike itself, release and debug.
#  2. scripts/run_determinism.sh, every part: spikes/out/integration/, session-sim/, r18/,
#     p2p-v2/, r15/hooks.log, perturbation-history/, the wasm module hashes and the MCP session.
#     Its physics part then checks the new baselines (trace release == debug, goldens, rollback).
#  3. scripts/run_p2_2_tests.sh --linux: spikes/out/p2-2/ (Windows and Linux, debug and release,
#     plus the fork suite), which also checks that pe-physics reproduces the new baselines.
#  4. scripts/regress_session_sim.sh: the new session logs reproduce (CPU timings masked).
# Records not written here are historical evidence of a named commit (f32 builds), listed in
# the doc; they stay as they are.
set -euo pipefail
cd "$(dirname "$0")/.."
linux=--linux
[ "${1:-}" = --no-linux ] && linux=""
# PE_HEAVY: an optional wrapper script every cargo job runs through (as in run_p2_2_tests.sh).
low() { if [ -n "${PE_HEAVY:-}" ]; then bash "$PE_HEAVY" "$@"; else "$@"; fi; }
step() { echo; echo "== $*"; }

step "build the physics spike (release and debug)"
low cargo build --release -q -p pe-spike-physics
low cargo build -q -p pe-spike-physics

step "1. physics baselines in spikes/out/vdw"
d=spikes/out/vdw
for b in release debug; do
  if [ $b = release ]; then P=target/release/pe-spike-physics; else P=target/debug/pe-spike-physics; fi
  for m in vdw off; do
    fl=""; [ $m = off ] && fl="--upstream"
    $P $fl goldens > $d/goldens-$m-win-$b.log 2>&1
    $P $fl trace 600 $d/trace-$m-win-$b.txt > $d/trace-$m-win-$b.log 2>&1
    $P $fl images $d/images-$m-win-$b.txt > $d/images-$m-win-$b.log 2>&1
    $P $fl rollback > $d/rollback-$m-win-$b.log 2>&1
    for f in goldens rollback; do
      grep -q "RESULT: PASS" $d/$f-$m-win-$b.log || { echo "FAIL: $f $m $b"; tail -5 $d/$f-$m-win-$b.log; exit 1; }
    done
    echo "$b $m: goldens PASS, rollback PASS, $(grep -o 'digest [0-9a-f]*' $d/trace-$m-win-$b.log)"
  done
  cmp -s $d/trace-vdw-win-$b.txt $d/trace-vdw-win-release.txt || { echo "FAIL: trace $b differs from release"; exit 1; }
done

step "2. run_determinism.sh (every part)"
bash scripts/run_determinism.sh

step "3. run_p2_2_tests.sh $linux"
bash scripts/run_p2_2_tests.sh $linux

step "4. regress_session_sim.sh"
low bash scripts/regress_session_sim.sh --jobs 2

step "done: review the diff (git status -- spikes/out), then commit it"
git status --short -- spikes/out | head -80
