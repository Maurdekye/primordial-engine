def crate_toml(name, deps, cdylib=False, rlib_too=False):
    s = f'[package]\nname = "{name}"\nversion = "0.0.1"\nedition.workspace = true\nlicense.workspace = true\npublish.workspace = true\n'
    if cdylib:
        s += '\n[lib]\ncrate-type = ["cdylib"]\n'
    if deps:
        s += "\n[dependencies]\n" + "".join(f'{d} = {{ path = "../{d}" }}\n' for d in deps)
    return s


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def main():
    args = sys.argv[1:]
    scale = int(args[args.index("--scale") + 1]) if "--scale" in args else 1
    out = args[args.index("--out") + 1] if "--out" in args else os.path.join(ROOT, "spikes", "iter-bench", "guests")
    rnd = random.Random(20261030 + scale)
    src = gen_systems(scale, rnd)
    loc = 0

    def emit(path, text):
        nonlocal loc
        loc += text.count("\n")
        write(os.path.join(out, path), HEADER + text)

    write(os.path.join(out, "Cargo.toml"), sub(WS_TOML, sysmembers=", ".join(f'"{s}"' for s in SYSTEMS)))
    # ---- split
    write(os.path.join(out, "pe_api", "Cargo.toml"), crate_toml("pe_api", []))
    emit("pe_api/src/lib.rs", API_ROOT)
    emit("pe_api/src/math.rs", src["math"])
    emit("pe_api/src/query.rs", QUERY)
    emit("pe_api/src/world.rs", WORLD)
    split_loc = loc
    for s in SYSTEMS:
        write(os.path.join(out, s, "Cargo.toml"), crate_toml(s, ["pe_api"]))
        emit(f"{s}/src/lib.rs", "use pe_api::*;\n" + src[s])
    write(os.path.join(out, "logic_game", "Cargo.toml"), crate_toml("logic_game", ["pe_api"] + SYSTEMS))
    emit("logic_game/src/lib.rs", "use pe_api::*;\n" + GAME)
    write(os.path.join(out, "logic_wasm", "Cargo.toml"), crate_toml("logic_wasm", ["pe_api", "logic_game"], cdylib=True))
    emit("logic_wasm/src/lib.rs", "use logic_game::*;\nuse pe_api::*;\n" +
         sub(WASM_GLUE, tick="tick(world(), frame, mask, &mut WasmHost)") + WASM_GLUE_GAME_EXPORTS)
    split_loc = loc
    # ---- mono (same text, as modules of one crate)
    write(os.path.join(out, "logic_mono", "Cargo.toml"), crate_toml("logic_mono", [], cdylib=True))
    mods = "pub mod api;\npub mod game;\n" + "".join(f"pub mod {s};\n" for s in SYSTEMS) + \
        "\nuse api::*;\nuse game::*;\n" + sub(WASM_GLUE, tick="tick(world(), frame, mask, &mut WasmHost)") + \
        WASM_GLUE_GAME_EXPORTS
    write(os.path.join(out, "logic_mono", "src", "lib.rs"), HEADER + mods)
    write(os.path.join(out, "logic_mono", "src", "api", "mod.rs"), HEADER + API_ROOT)
    write(os.path.join(out, "logic_mono", "src", "api", "math.rs"), HEADER + src["math"])
    write(os.path.join(out, "logic_mono", "src", "api", "query.rs"), HEADER + QUERY)
    write(os.path.join(out, "logic_mono", "src", "api", "world.rs"), HEADER + WORLD)
    for s in SYSTEMS:
        write(os.path.join(out, "logic_mono", "src", f"{s}.rs"), HEADER + "use crate::api::*;\n" + src[s])
    write(os.path.join(out, "logic_mono", "src", "game.rs"),
          HEADER + "use crate::api::*;\nuse crate::{" + ", ".join(SYSTEMS) + "};\n" + GAME)
    # ---- per-system module
    write(os.path.join(out, "mod_movement", "Cargo.toml"),
          crate_toml("mod_movement", ["pe_api", "sys_movement"], cdylib=True))
    write(os.path.join(out, "mod_movement", "src", "lib.rs"), HEADER + "use pe_api::*;\n" +
          sub(WASM_GLUE, tick="let w = world();\n    w.frame = frame;\n    let _ = mask;\n    w.rebuild_grid();\n"
                              "    sys_movement::run(w, &mut WasmHost)"))
    write(os.path.join(out, "logic_native", "Cargo.toml"),
          crate_toml("logic_native", ["pe_api", "logic_game"], cdylib=True))
    write(os.path.join(out, "logic_native", "src", "lib.rs"), HEADER + "use logic_game::*;\nuse pe_api::*;\n" + NATIVE_GLUE)
    print(f"generated {out} (scale {scale}): {split_loc} lines in the split crates "
          f"(pe_api {sum(1 for _ in open(os.path.join(out, 'pe_api/src/math.rs')))} math lines)")


if __name__ == "__main__":
    main()
